#!/bin/bash
# Reproduce the staged Unity project; never resync or edit the upstream GLB/Blender sources.
set -euo pipefail

usage() {
  cat <<'HELP'
Usage: Scripts/rebuild-macos.sh [--build-only] [--dry-run]

Default: refresh the locked URP imports, regenerate FarmWorld and review images,
check the actual static/contact reports, then build a macOS development player.
--build-only  Build the currently generated scene, requiring its current stamps.
--dry-run     Read-only preflight and command listing; never launch Unity.

Set LULU_UNITY_EDITOR to Unity.app or Contents/MacOS/Unity when installed elsewhere.
Close this project's Unity Editor before a real run. Generated Prefabs/scene/settings
are regenerated by the existing Editor methods; save authored edits separately first.
Existing LuluFarm.app is archived before the build. Source GLBs are not resynced.
Build success does not establish visual, manual-route or device-performance acceptance.
HELP
}

build_only=0
dry_run=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --build-only) build_only=1 ;;
    --dry-run) dry_run=1 ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'Unknown option: %s\n' "$1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
project_dir=$(CDPATH= cd -- "$script_dir/.." && pwd)
cd "$project_dir"
command -v python3 >/dev/null || { printf 'Python 3 is required for lock/report checks.\n' >&2; exit 2; }

editor=${LULU_UNITY_EDITOR:-}
if [ -z "$editor" ]; then
  for candidate in \
    "$project_dir/../.unity-install/Editors/6000.3.16f1/Unity.app" \
    '/Applications/Unity/Hub/Editor/6000.3.16f1/Unity.app'; do
    if [ -x "$candidate/Contents/MacOS/Unity" ]; then editor=$candidate; break; fi
  done
fi
case "$editor" in *.app) editor="$editor/Contents/MacOS/Unity" ;; esac
[ -x "$editor" ] || { printf 'Set LULU_UNITY_EDITOR to the installed Unity 6000.3.16f1 editor.\n' >&2; exit 2; }

python3 - "$project_dir" "$editor" "$build_only" <<'PY'
import hashlib, json, pathlib, plistlib, re, sys
root, binary = map(pathlib.Path, sys.argv[1:3])
actual = plistlib.loads((binary.parent.parent / 'Info.plist').read_bytes())['CFBundleVersion']
project = re.search(r'^m_EditorVersion: (.+)$', (root/'ProjectSettings/ProjectVersion.txt').read_text(), re.M)[1]
if actual != '6000.3.16f1' or project != actual:
    raise SystemExit(f'Editor mismatch: installed={actual}, project={project}; expected 6000.3.16f1')
manifest = json.loads((root/'Packages/manifest.json').read_text())['dependencies']
locked = json.loads((root/'Packages/packages-lock.json').read_text())['dependencies']
expected = {'com.unity.render-pipelines.universal':'17.3.0', 'com.unity.cinemachine':'3.1.5',
            'com.unity.inputsystem':'1.14.2', 'com.unity.cloud.gltfast':'6.20.0'}
for name, version in expected.items():
    if manifest.get(name) != version or locked.get(name, {}).get('version') != version:
        raise SystemExit(f'Package mismatch: {name}; expected manifest and lock = {version}')
for name, version in manifest.items():
    if locked.get(name, {}).get('version') != version:
        raise SystemExit(f'Direct dependency differs from lock: {name}')
    cached = []
    for path in (root/'Library/PackageCache').glob(name+'*/package.json'):
        data = json.loads(path.read_text())
        if data.get('name') == name: cached.append(data.get('version'))
    if cached and version not in cached:
        raise SystemExit(f'Resolved package cache mismatch: {name}: {cached}, expected {version}')
policy = root/'Assets/Farm/Editor/ImportPolicy/FarmAssetImportPolicy.cs'
if not policy.is_file(): raise SystemExit('Missing persistent glTF normal encoding import policy')
normal_count = 0
for path in (root/'Assets/Farm/Art').rglob('*_normal*.meta'):
    if '/Lulu/' in path.as_posix(): continue
    text = path.read_text(); kind = re.search(r'^  textureType: (\d+)', text, re.M)
    srgb = re.search(r'^    sRGBTexture: (\d+)', text, re.M)
    if not kind or kind[1] != '0' or not srgb or srgb[1] != '0':
        raise SystemExit(f'Normal encoding regression (expected Default + linear): {path}')
    normal_count += 1
for required in ['Assets/Farm/Data/asset-registry.json', 'Assets/Farm/Editor/FarmWorldReview.cs']:
    if not (root/required).is_file(): raise SystemExit(f'Missing project file: {required}')
if sys.argv[3] == '1':
    stamp_path = root/'Evidence/scene-generation-status.json'
    if not stamp_path.is_file() or not (root/'Assets/Farm/Scenes/FarmWorld.unity').is_file():
        raise SystemExit('Build-only requires an already generated FarmWorld and scene-generation stamp')
    stamp = json.loads(stamp_path.read_text())
    digest = hashlib.sha256((root/'Assets/Farm/Data/asset-registry.json').read_bytes()).hexdigest()
    if stamp.get('registrySHA256') != digest or stamp.get('status') != 'generated_pending_actual_play_and_visual_checks' or stamp.get('issues'):
        raise SystemExit('Build-only stamp is stale or reports issues; run the complete rebuild first')
print(f'Preflight: editor/package locks match; {normal_count} non-Lulu normal metadata files retain Default + linear. No runtime acceptance implied.')
PY

if [ -e "$project_dir/Temp/UnityLockfile" ]; then
  printf 'This project has a Unity lockfile; close its Editor before a real run. The script never removes locks.\n' >&2
  if [ "$dry_run" -eq 0 ]; then exit 2; fi
fi

run_id=$(date -u +%Y%m%d-%H%M%S)-$$
run_dir="$project_dir/Evidence/rebuild-macos-$run_id"
methods=()
if [ "$build_only" -eq 0 ]; then
  methods+=(LuluFarm.Editor.FarmProjectBuilder.RefreshMaterialsAndImport)
  methods+=(LuluFarm.Editor.FarmWorldReview.GenerateAndReview)
fi
methods+=(LuluFarm.Editor.FarmProjectBuilder.BuildMac)

if [ "$dry_run" -eq 1 ]; then
  printf 'Read-only dry run. Planned evidence: %s\n' "$run_dir"
  for method in "${methods[@]}"; do
    label=${method##*.}
    printf '  '
    printf '%q ' "$editor" -batchmode -quit -projectPath "$project_dir" -buildTarget StandaloneOSX -executeMethod "$method" -logFile "$run_dir/$label.log"
    printf '\n'
  done
  printf 'No Unity process, output folder, model change or build was created.\n'
  exit 0
fi

mkdir -p "$run_dir/before"
for file in Packages/manifest.json Packages/packages-lock.json ProjectSettings/ProjectVersion.txt \
  Assets/Farm/Data/asset-registry.json Assets/Farm/Scenes/FarmWorld.unity \
  Evidence/import-stamp.json Evidence/scene-generation-status.json Evidence/build-macOS.json; do
  if [ -f "$file" ]; then
    mkdir -p "$run_dir/before/$(dirname "$file")"
    cp -p "$file" "$run_dir/before/$file"
  fi
done

python3 - "$run_dir" <<'PY'
import hashlib, json, pathlib, sys
out = pathlib.Path(sys.argv[1])
files = {}
for folder in ['Assets/Farm/Art/Lulu', 'Assets/Farm/Art/Comparisons/Lulu']:
    for path in sorted(pathlib.Path(folder).rglob('*')):
        if path.is_file(): files[path.as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
if not files: raise SystemExit('No frozen staged Lulu files found; stopping before Unity launch')
(out/'before/frozen-lulu-sha256.json').write_text(json.dumps(files, indent=2))
policy = pathlib.Path('Assets/Farm/Editor/ImportPolicy/FarmAssetImportPolicy.cs')
(out/'before/normal-import-policy.sha256').write_text(hashlib.sha256(policy.read_bytes()).hexdigest())
PY

check_locks() {
  cmp -s Packages/manifest.json "$run_dir/before/Packages/manifest.json" && \
    cmp -s Packages/packages-lock.json "$run_dir/before/Packages/packages-lock.json" || {
      printf 'Package resolution changed a lock file. Stopping; inspect changes and logs, no automatic rollback.\n' >&2
      exit 1
    }
}

for method in "${methods[@]}"; do
  label=${method##*.}
  touch "$run_dir/$label.started"
  if [ "$label" = BuildMac ] && [ -d Builds/macOS/LuluFarm.app ]; then
    archive="Builds/macOS/archive/$run_id"
    mkdir -p "$archive"
    mv Builds/macOS/LuluFarm.app "$archive/LuluFarm.app"
    printf 'Previous app preserved: %s\n' "$project_dir/$archive/LuluFarm.app"
  fi
  printf 'Executing %s\nLog: %s\n' "$method" "$run_dir/$label.log"
  if "$editor" -batchmode -quit -projectPath "$project_dir" -buildTarget StandaloneOSX \
    -executeMethod "$method" -logFile "$run_dir/$label.log"; then
    check_locks
  else
    status=$?
    printf 'Unity failed (exit %s): %s\n' "$status" "$run_dir/$label.log" >&2
    exit "$status"
  fi

  # These checks distinguish an actual report from a stale success left by an earlier run.
  python3 - "$label" "$run_dir" <<'PY'
import hashlib, json, pathlib, re, shutil, sys
label, output = sys.argv[1], pathlib.Path(sys.argv[2])
started = (output/f'{label}.started').stat().st_mtime
expected_lulu = json.loads((output/'before/frozen-lulu-sha256.json').read_text())
current_lulu = {}
for folder in ['Assets/Farm/Art/Lulu', 'Assets/Farm/Art/Comparisons/Lulu']:
    for path in sorted(pathlib.Path(folder).rglob('*')):
        if path.is_file(): current_lulu[path.as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
if expected_lulu != current_lulu:
    raise SystemExit('Frozen Lulu staged payload/metadata changed. Stop and inspect; no automatic rollback.')
policy = pathlib.Path('Assets/Farm/Editor/ImportPolicy/FarmAssetImportPolicy.cs')
if hashlib.sha256(policy.read_bytes()).hexdigest() != (output/'before/normal-import-policy.sha256').read_text():
    raise SystemExit('Normal import policy changed during the build')
normal_files = []
for path in pathlib.Path('Assets/Farm/Art').rglob('*_normal*.meta'):
    if '/Lulu/' in path.as_posix(): continue
    text = path.read_text(); kind = re.search(r'^  textureType: (\d+)', text, re.M)
    srgb = re.search(r'^    sRGBTexture: (\d+)', text, re.M)
    if not kind or kind[1] != '0' or not srgb or srgb[1] != '0':
        raise SystemExit(f'Normal encoding regression after {label}: {path}')
    normal_files.append(str(path))
manifest = json.loads(pathlib.Path('Packages/manifest.json').read_text())['dependencies']
resolved = []
for name, version in manifest.items():
    matches = []
    for path in pathlib.Path('Library/PackageCache').glob(name+'*/package.json'):
        data = json.loads(path.read_text())
        if data.get('name') == name and data.get('version') == version: matches.append(str(path))
    if not matches: raise SystemExit(f'No matching resolved package.json after Unity: {name} {version}')
    resolved.append({'name':name, 'version':version, 'package_json':matches})
(output/f'{label}-preservation-check.json').write_text(json.dumps({
    'scope':'file/configuration checks only; not visual or runtime acceptance',
    'lulu_payload_and_metadata_unchanged':True, 'normal_encoding':'Default_and_linear',
    'normal_metadata_count':len(normal_files), 'resolved_direct_packages':resolved}, indent=2))
def report(path, wanted, key='status'):
    path = pathlib.Path(path)
    if not path.is_file() or path.stat().st_mtime < started:
        raise SystemExit(f'Missing or stale executed report: {path}')
    data = json.loads(path.read_text())
    if data.get(key) != wanted: raise SystemExit(f'Unsuccessful report: {path}: {data.get(key)}')
    shutil.copy2(path, output/f'{label}-{path.name}')
    return data
if label == 'RefreshMaterialsAndImport':
    report('Evidence/import-stamp.json', 'imported_pending_visual_review')
elif label == 'GenerateAndReview':
    report('Evidence/scene-generation-status.json', 'generated_pending_actual_play_and_visual_checks')
    report('Evidence/scene-contact-audit.json', 'technical_probes_pass_manual_visual_pending')
    candidates = list(pathlib.Path('Evidence/acceptance').glob('*/static-validation.json'))
    if not candidates: raise SystemExit('No static validation report was written')
    report(max(candidates, key=lambda p:p.stat().st_mtime), 'static_checks_pass_runtime_and_visual_pending')
elif label == 'BuildMac':
    data = report('Evidence/build-macOS.json', 'Succeeded', 'result')
    if data.get('errors', 1) != 0: raise SystemExit('Build report has errors')
    # The bundle executable follows PlayerSettings.productName, so consult Info.plist.
    import plistlib
    bundle = pathlib.Path('Builds/macOS/LuluFarm.app')
    info = plistlib.loads((bundle/'Contents/Info.plist').read_bytes())
    executable = bundle/'Contents/MacOS'/info['CFBundleExecutable']
    if not executable.is_file(): raise SystemExit('Built app executable is missing')
    print(f'Built development app: {bundle.resolve()}')
PY
done

printf 'Build reports retained: %s\n' "$run_dir"
printf 'Development build only. Actual route, visuals, user art and device performance still require separate evidence.\n'
